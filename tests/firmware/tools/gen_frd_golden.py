#!/usr/bin/env python3
"""Generate FRD-frame golden vectors from M2's REAL IMU simulator (simulation/generator/imu_simulator.py).

Output: tests/firmware/test/test_sim_frd/frd_golden.h  (true roll + FRD IMU samples at 20 Hz).
The C test (test_sim_frd) converts FRD -> M1 sensor frame and checks the roll recovered by the C pipeline.
Run from the repo root:  python tests/firmware/tools/gen_frd_golden.py
"""
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
sys.path.insert(0, ROOT)
from simulation.generator.imu_simulator import IMUSimulator  # noqa: E402
from simulation.generator.roll_dynamics import RollState  # noqa: E402

N, DT = 1400, 0.05
sim = IMUSimulator(seed=12345)
rows = []
for i in range(N):
    t = i * DT
    # True roll: +3 deg static heel, 8 deg swing (10 s period) + 2 deg swing (4 s period).
    # Positive = starboard down (right-hand rule about +X in FRD).
    w1, w2 = 2 * math.pi / 10.0, 2 * math.pi / 4.0
    phi = math.radians(3.0) + math.radians(8.0) * math.sin(w1 * t) + math.radians(2.0) * math.sin(w2 * t)
    om = math.radians(8.0) * w1 * math.cos(w1 * t) + math.radians(2.0) * w2 * math.cos(w2 * t)
    s = sim.sample(RollState(phi, om, t), 0.0)
    rows.append((phi, s.ax, s.ay, s.az, s.gx, s.gy, s.gz))

out = os.path.join(ROOT, "tests", "firmware", "test", "test_sim_frd", "frd_golden.h")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", newline="\n", encoding="utf-8") as f:
    f.write("/* AUTO-GENERATED by tests/firmware/tools/gen_frd_golden.py from simulation/generator/imu_simulator.py (M2). Do not edit. */\n")
    f.write("#define FRD_N %d\n#define FRD_DT 0.05f\n" % N)
    f.write("static const float FRD_PHI[FRD_N] = {%s};\n" % ",".join("%.9g" % r[0] for r in rows))
    for k, name in enumerate(["AX", "AY", "AZ", "GX", "GY", "GZ"], start=1):
        f.write("static const float FRD_%s[FRD_N] = {%s};\n" % (name, ",".join("%.9g" % r[k] for r in rows)))
print("wrote", out, N, "samples")
