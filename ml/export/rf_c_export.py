"""Exporter RandomForestClassifier nhị phân (sklearn) -> C99 độc lập cho demo thử nghiệm CÔ LẬP. KHÔNG phải model
firmware: không sinh ml/export/model.h, không dùng svmg_class_t, không đăng ký svmg_engine_set_rf(). pred: 0 = proxy-NEG,
1 = proxy-POS, -1 = đầu vào lỗi. sklearn ép X về float32 và so sánh ``x <= t64``; ngưỡng lưu là float32 lớn nhất <= t64
nên với x float32 ``x <= t32`` <=> ``x <= t64`` (chính xác). Lá lưu P(POS) float32; điểm = trung bình lá (cộng double).
"""
from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
from pathlib import Path

import numpy as np
from sklearn.ensemble import RandomForestClassifier

STATUS = {"OK": 0, "ERR_NULL": -1, "ERR_LENGTH": -2, "ERR_NONFINITE": -3}
RUNNER_SOURCE = Path(__file__).with_name("rf_demo_runner.c")
CFLAGS = ("-std=c99", "-O2", "-Wall", "-Wextra", "-Werror", "-pedantic")


def floor_float32(value: float) -> np.float32:
    t = np.float32(value)
    return np.nextafter(t, np.float32(-np.inf)) if float(t) > value else t


def flatten_forest(model: RandomForestClassifier, n_features: int) -> dict:
    if not isinstance(model, RandomForestClassifier) or [int(c) for c in model.classes_] != [0, 1]:
        raise ValueError("Chỉ hỗ trợ RandomForestClassifier nhị phân với classes_ == [0, 1].")
    if model.n_features_in_ != n_features:
        raise ValueError(f"Model có {model.n_features_in_} feature, contract yêu cầu {n_features}.")
    feature, value, left, right, roots = [], [], [], [], []
    for estimator in model.estimators_:
        tree, base = estimator.tree_, len(feature)
        roots.append(base)
        for node in range(tree.node_count):
            if tree.children_left[node] == -1:
                counts = tree.value[node, 0]
                feature.append(-1), value.append(np.float32(counts[1] / counts.sum())), left.append(-1), right.append(-1)
            else:
                feature.append(int(tree.feature[node]))
                value.append(floor_float32(float(tree.threshold[node])))
                left.append(base + int(tree.children_left[node])), right.append(base + int(tree.children_right[node]))
    if len(feature) > 32767:
        raise ValueError("Quá nhiều nút cho chỉ số int16_t.")
    return {"feature": feature, "value": value, "left": left, "right": right, "roots": roots}


def _array(ctype: str, name: str, items: list[str], per_line: int = 12) -> str:
    rows = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return f"static const {ctype} {name}[{len(items)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def generate_c(model: RandomForestClassifier, feature_names: list[str], metadata: dict, name: str,
               threshold: float = 0.5) -> tuple[str, str, dict]:
    """Trả (header, source, stats). ``name`` là tiền tố C và tên file (vd. ``svmg_rf_proxy_demo``)."""
    flat, up, n = flatten_forest(model, len(feature_names)), name.upper(), len(feature_names)
    meta = json.dumps({**metadata, "feature_names": feature_names}, ensure_ascii=True, sort_keys=True)
    defines = [f"#define {up}_N_FEATURES {n}", f"#define {up}_N_TREES {len(flat['roots'])}",
               f"#define {up}_N_NODES {len(flat['feature'])}", f"#define {up}_THRESHOLD {float(threshold)!r}",
               f"#define {up}_PRED_NEG 0", f"#define {up}_PRED_POS 1", f"#define {up}_PRED_INVALID (-1)",
               *(f"#define {up}_{k} ({v})" for k, v in STATUS.items()),
               f"#define {up}_FEATURE_ORDER_SHA256 \"{hashlib.sha256(chr(10).join(feature_names).encode()).hexdigest()}\"",
               f"#define {up}_METADATA_JSON {json.dumps(meta)}"]
    header = (f"/* GENERATED by ml/export/rf_c_export.py. EXPERIMENTAL ISOLATED DEMO - NOT a production firmware model.\n"
              f" * Binary proxy output only; NOT svmg_class_t; do NOT register with svmg_engine_set_rf(). */\n"
              f"#ifndef {up}_H\n#define {up}_H\n#include <stddef.h>\n\n" + "\n".join(defines) + "\n\n"
              f"typedef struct {{ int pred; float score; }} {name}_output_t;\n\n"
              f"extern const char *const {name}_feature_names[{up}_N_FEATURES];\n"
              f"/* features: {n} float32 in feature_names order. Returns {up}_OK or an error code < 0;\n"
              f" * on error: out->pred = {up}_PRED_INVALID, out->score = -1. */\n"
              f"int {name}_predict(const float *features, size_t n_features, {name}_output_t *out);\n\n#endif\n")
    hexf = [float(v).hex() + "f" for v in flat["value"]]
    source = (f"/* GENERATED by ml/export/rf_c_export.py - do not edit. Experimental isolated demo. */\n"
              f"#include \"{name}.h\"\n#include <math.h>\n#include <stdint.h>\n\n"
              f"/* VALUE: float32 threshold rounded toward -inf (internal); P(proxy-POS) at leaves (FEATURE == -1). */\n"
              + _array("int8_t", "FEATURE", [str(v) for v in flat["feature"]], 24)
              + _array("float", "VALUE", hexf, 6)
              + _array("int16_t", "LEFT", [str(v) for v in flat["left"]], 16)
              + _array("int16_t", "RIGHT", [str(v) for v in flat["right"]], 16)
              + _array("int16_t", "ROOT", [str(v) for v in flat["roots"]], 16)
              + f"\nconst char *const {name}_feature_names[{up}_N_FEATURES] = {{\n    "
              + ",\n    ".join(json.dumps(f) for f in feature_names) + "\n};\n\n"
              f"int {name}_predict(const float *x, size_t n_features, {name}_output_t *out) {{\n"
              f"    size_t i;\n    int t;\n    double acc = 0.0;\n"
              f"    if (x == NULL || out == NULL) {{ return {up}_ERR_NULL; }}\n"
              f"    out->pred = {up}_PRED_INVALID;\n    out->score = -1.0f;\n"
              f"    if (n_features != {up}_N_FEATURES) {{ return {up}_ERR_LENGTH; }}\n"
              f"    for (i = 0; i < n_features; ++i) {{ if (!isfinite(x[i])) {{ return {up}_ERR_NONFINITE; }} }}\n"
              f"    for (t = 0; t < {up}_N_TREES; ++t) {{\n        int16_t k = ROOT[t];\n"
              f"        while (FEATURE[k] >= 0) {{ k = (x[FEATURE[k]] <= VALUE[k]) ? LEFT[k] : RIGHT[k]; }}\n"
              f"        acc += (double)VALUE[k];\n    }}\n    acc /= (double){up}_N_TREES;\n"
              f"    out->score = (float)acc;\n    out->pred = (acc >= {up}_THRESHOLD) ? {up}_PRED_POS : {up}_PRED_NEG;\n"
              f"    return {up}_OK;\n}}\n")
    nodes, trees = len(flat["feature"]), len(flat["roots"])
    stats = {"n_trees": trees, "total_nodes": nodes, "leaves": int(sum(f < 0 for f in flat["feature"])),
             "max_depth": int(max(e.tree_.max_depth for e in model.estimators_)),
             "model_array_bytes": nodes * (1 + 4 + 2 + 2) + trees * 2}
    return header, source, stats


def write_c(model, feature_names: list[str], metadata: dict, out_dir: Path, name: str) -> dict:
    header, source, stats = generate_c(model, feature_names, metadata, name)
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {"header": out_dir / f"{name}.h", "source": out_dir / f"{name}.c"}
    paths["header"].write_text(header, encoding="ascii")
    paths["source"].write_text(source, encoding="ascii")
    digest = hashlib.sha256((header + source).encode()).hexdigest()
    return {**stats, "paths": paths, "generated_sha256": digest,
            "generated_bytes": {k: p.stat().st_size for k, p in paths.items()}}


def build_runner(export: dict, name: str, build_dir: Path, compiler: str | None = None) -> Path:
    cc = compiler or shutil.which("cc") or shutil.which("clang")
    if not cc:
        raise RuntimeError("Không tìm thấy trình biên dịch C (cc/clang).")
    binary = build_dir / f"{name}_runner"
    cmd = [cc, *CFLAGS, f"-DRF_DEMO_HEADER=\"{name}.h\"", f"-DRF_DEMO_PREDICT={name}_predict", f"-DRF_DEMO_OUTPUT={name}_output_t",
           "-I", str(export["paths"]["header"].parent), str(export["paths"]["source"]), str(RUNNER_SOURCE), "-lm", "-o", str(binary)]
    subprocess.run(cmd, check=True, capture_output=True, text=True)
    return binary


def object_size(source: Path, compiler: str, size_tool: str, out: Path) -> dict:
    """Kích thước section của object model (biên dịch -Os -c), dạng Berkeley ``size``."""
    subprocess.run([compiler, "-std=c99", "-Os", "-c", "-I", str(source.parent), str(source), "-o", str(out)],
                   check=True, capture_output=True, text=True)
    lines = subprocess.run([size_tool, str(out)], check=True, capture_output=True, text=True).stdout.split("\n")
    return dict(zip(lines[0].split()[:4], (int(v) for v in lines[1].split()[:4])))


def run_vectors(binary: Path, rows: list) -> list[tuple[int, int, float]]:
    """Chạy runner C: mỗi dòng float32 dạng hex chính xác; trả (status, pred, score)."""
    text = "\n".join(",".join(float(np.float32(v)).hex() for v in row) for row in rows) + "\n"
    proc = subprocess.run([str(binary)], input=text, capture_output=True, text=True, check=True)
    out = [line.split(",") for line in proc.stdout.strip().split("\n")]
    if len(out) != len(rows):
        raise RuntimeError(f"Runner trả {len(out)} dòng cho {len(rows)} vector.")
    return [(int(s), int(p), float.fromhex(v)) for s, p, v in out]
